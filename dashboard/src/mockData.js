export function computeStats(deals) {
  const total = deals.length;
  const avg = deals.reduce((acc, d) => acc + (d.margin_pct || 0), 0) / (total || 1);
  const sorted = [...deals].sort((a, b) => (b.margin_pct || 0) - (a.margin_pct || 0));
  const best = sorted[0] || null;
  return {
    total_deals_today: total,
    avg_margin_pct: Math.round(avg * 10) / 10,
    best_deal: best ? {
      title: best.title,
      gross_margin_eur: best.gross_margin_eur,
      margin_pct: best.margin_pct
    } : null
  };
}
